"""Billing Foundation (M9.2) — pure domain for the revenue plane.

Business rules only (ADR-0023 §Decision 10): aggregates, lifecycles, policies, validation,
diagnostics, events, repository **interfaces**, stateless services, factories, and DTOs.

**Nothing here performs I/O.** No HTTP, no FastAPI, no SQL, no ORM, no persistence
implementation, no networking, no vendor SDK, no payment execution, no tax provider. Time
and id minting arrive through injected seams; event emission is an injected seam; storage
is an interface someone else implements (M9.4, inside the Epic 8 persistence layer).

Imports: `platform/core/` and the standard library only (ADR-0031 IR1).
"""

