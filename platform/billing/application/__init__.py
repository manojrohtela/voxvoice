"""`billing.application` — the Billing Application layer (Epic 9, M9.3).

The CQRS orchestration layer between a future Control Plane and the M9.2 Foundation. It
owns commands, queries, the two buses, use cases, transaction boundaries (Unit of Work),
authorization *orchestration*, DTO mapping, application-level events, and the composition
facade.

**It owns no business rules.** Validation, construction, lifecycle legality, money
arithmetic, proration, entitlement composition, quota derivation, invoice totals, and
numbering all remain Foundation behaviour that these use cases call.

Boundaries (ADR-0031, test-enforced): `billing.application → billing.foundation, core,
stdlib` — no persistence, no SQL, no FastAPI/HTTP, no Control Plane, no runtime, no
execution platform, no provider adapter, no Product Runtime, no deployment, no knowledge,
no observability. The Foundation is byte-for-byte unchanged by this milestone.
"""

