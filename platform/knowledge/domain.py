"""Knowledge domain model (M5.2B-1) — immutable value objects.

The vocabulary the Knowledge Runtime curates: documents, their immutable versions, and
the chunks they project into. Everything is frozen + slotted (deterministic, cheap,
replay-friendly). No behaviour beyond pure derivations; no storage, no retrieval, no
ranking (later milestones).
"""

from __future__ import annotations

from dataclasses import dataclass, field, replace
from enum import StrEnum


class KnowledgeType(StrEnum):
    """What a document *is* (independent of where it is stored)."""

    STATIC = "static"  # fixed reference material
    ORGANIZATION = "organization"  # org-wide corpus
    PRIVATE = "private"  # user/agent-private
    SHARED = "shared"  # explicitly shared/granted
    IMPORTED = "imported"  # externally sourced upload
    GENERATED = "generated"  # produced elsewhere, registered here (never generated by us)
    REFERENCE = "reference"  # canonical citeable source
    EXTERNAL = "external"  # future: federated/remote source


class ImportOrigin(StrEnum):
    IMPORTED = "imported"
    GENERATED = "generated"
    REFERENCE = "reference"


class DocumentState(StrEnum):
    IMPORTED = "imported"
    VALIDATED = "validated"
    PARSED = "parsed"
    CHUNKED = "chunked"
    EMBEDDED = "embedded"
    INDEXED = "indexed"
    ACTIVE = "active"
    ARCHIVED = "archived"
    DELETED = "deleted"


class ChunkState(StrEnum):
    CREATED = "created"
    EMBEDDED = "embedded"
    INDEXED = "indexed"
    ARCHIVED = "archived"
    DELETED = "deleted"


@dataclass(frozen=True, slots=True)
class KnowledgeScope:
    """Ownership/isolation keys for a document. `department` is an additive scope
    dimension carried here (the core scope is frozen)."""

    org_id: str | None = None
    user_id: str | None = None
    department: str | None = None


@dataclass(frozen=True, slots=True)
class SourceDescriptor:
    """Where a document came from (never interpreted — recorded)."""

    uri: str
    mime: str = "text/plain"
    origin: ImportOrigin = ImportOrigin.IMPORTED
    title: str | None = None
    extra: dict[str, str] = field(default_factory=dict)


@dataclass(frozen=True, slots=True)
class KnowledgeMetadata:
    """Descriptive envelope for a document. Additive with defaults — old records
    deserialize unchanged (backward compatible)."""

    title: str | None = None
    author: str | None = None
    lang: str = "und"
    source_uri: str | None = None
    mime: str | None = None
    origin: str | None = None
    content_hash: str | None = None
    confidence: float = 1.0
    tags: tuple[str, ...] = ()
    created_at: float = 0.0
    updated_at: float = 0.0
    extra: dict[str, str] = field(default_factory=dict)


@dataclass(frozen=True, slots=True)
class Chunk:
    """A retrievable slice of a document version. Identity is content-derived, so an
    unchanged chunk keeps its id (and embedding) across versions."""

    id: str
    document_id: str
    version: int
    index: int
    content: str
    content_hash: str
    start: int
    end: int
    token_count: int
    strategy: str
    state: ChunkState = ChunkState.CREATED
    embedded: bool = False
    parent_id: str | None = None
    prev_id: str | None = None
    next_id: str | None = None
    metadata: dict[str, str] = field(default_factory=dict)

    def with_state(self, state: ChunkState) -> Chunk:
        return replace(self, state=state)

    def with_embedded(self, embedded: bool = True) -> Chunk:
        return replace(self, embedded=embedded)


@dataclass(frozen=True, slots=True)
class DocumentVersion:
    """An immutable snapshot of a document at one version number."""

    version_id: str
    document_id: str
    number: int
    content_hash: str
    created_at: float
    state: DocumentState = DocumentState.ACTIVE
    chunk_ids: tuple[str, ...] = ()

    def with_state(self, state: DocumentState) -> DocumentVersion:
        return replace(self, state=state)


@dataclass(frozen=True, slots=True)
class Document:
    """The document aggregate: identity + scope + type + lifecycle state + the current
    version's normalized text, content hash, chunk ids, and metadata. Raw bytes live in
    the object store; this record carries the normalized text for retrieval."""

    id: str
    scope: KnowledgeScope
    knowledge_type: KnowledgeType
    source: SourceDescriptor
    text: str
    content_hash: str
    version: int = 1
    version_id: str = ""
    state: DocumentState = DocumentState.IMPORTED
    metadata: KnowledgeMetadata = field(default_factory=KnowledgeMetadata)
    chunk_ids: tuple[str, ...] = ()

    # ── pure derivations (return a new document; never mutate) ───────────────
    def with_state(self, state: DocumentState) -> Document:
        return replace(self, state=state)

    def with_chunks(self, chunk_ids: tuple[str, ...]) -> Document:
        return replace(self, chunk_ids=chunk_ids)

    def with_version(self, number: int, version_id: str, content_hash: str) -> Document:
        return replace(self, version=number, version_id=version_id, content_hash=content_hash)

    def with_metadata(self, metadata: KnowledgeMetadata) -> Document:
        return replace(self, metadata=metadata)
